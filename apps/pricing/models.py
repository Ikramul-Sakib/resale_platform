"""
Pricing models for ValuLens.

PriceEstimate: computed valuation for an identified item.
MarketPriceObservation: raw market data points (asking or sold prices)
used as inputs to the pricing engine.
"""

from django.core.validators import MinValueValidator
from django.db import models


class PriceEstimate(models.Model):
    """
    A computed price estimate for an IdentifiedItem.

    Generated by the pricing service (pricing/services.py).
    Estimates are immutable snapshots — a new estimate is created
    each time the item is re-evaluated.

    source_type distinguishes how the estimate was produced:
    - market_data: calculated from MarketPriceObservations in the DB
    - model_generated: produced by an ML model or external API
    - manual: entered by a user or admin

    Money uses NUMERIC(12,2) via DecimalField. Never floats.
    """

    class SourceType(models.TextChoices):
        MARKET_DATA = "market_data", "Market Data"
        MODEL_GENERATED = "model_generated", "Model Generated"
        MANUAL = "manual", "Manual"

    identified_item = models.ForeignKey(
        "scans.IdentifiedItem",
        on_delete=models.CASCADE,
        related_name="price_estimates",
        help_text="The identified item this estimate is for.",
    )
    currency = models.CharField(
        max_length=3,
        default="USD",
        help_text="ISO 4217 currency code.",
    )
    price_min = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        help_text="Lower bound estimate (e.g. 25th percentile).",
    )
    price_typical = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        help_text="Central estimate (e.g. median).",
    )
    price_max = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        help_text="Upper bound estimate (e.g. 75th percentile).",
    )
    source_type = models.CharField(
        max_length=20,
        choices=SourceType.choices,
        help_text="How this estimate was produced.",
    )
    source_name = models.CharField(
        max_length=100,
        blank=True,
        default="",
        help_text="Name of the data source, e.g. 'valulens_v1', 'manual_entry'.",
    )
    sample_size = models.PositiveIntegerField(
        default=0,
        help_text="Number of observations used (0 for manual/model estimates).",
    )
    confidence = models.DecimalField(
        max_digits=3,
        decimal_places=2,
        null=True,
        blank=True,
        validators=[MinValueValidator(0)],
        help_text="Confidence score (0.00–1.00). Null if not applicable.",
    )
    uncertainty = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        null=True,
        blank=True,
        help_text="Uncertainty measure (e.g. std dev). Null if not applicable.",
    )
    methodology_version = models.CharField(
        max_length=20,
        default="v1",
        help_text="Version of the pricing methodology used.",
    )
    created_at = models.DateTimeField(auto_now_add=True, db_index=True)

    class Meta:
        db_table = "pricing_price_estimate"
        verbose_name = "price estimate"
        verbose_name_plural = "price estimates"
        ordering = ["-created_at"]
        constraints = [
            # min <= typical <= max
            models.CheckConstraint(
                name="ck_price_estimate_min_lte_typical",
                condition=models.Q(price_min__lte=models.F("price_typical")),
            ),
            models.CheckConstraint(
                name="ck_price_estimate_typical_lte_max",
                condition=models.Q(price_typical__lte=models.F("price_max")),
            ),
            # All prices must be >= 0
            models.CheckConstraint(
                name="ck_price_estimate_min_non_negative",
                condition=models.Q(price_min__gte=0),
            ),
        ]

    def __str__(self):
        return (
            f"Estimate for {self.identified_item}: "
            f"{self.currency} {self.price_min}–{self.price_typical}–{self.price_max}"
        )


class MarketPriceObservation(models.Model):
    """
    A raw market data point: an observed asking or sold price.

    Observations are collected from marketplaces and stored as immutable
    records. They feed the pricing engine (pricing/services.py).

    product_key is a normalized identifier (e.g. "nike-air-max-90-white")
    used for cross-scan aggregation. identified_item links to a specific
    scan result when applicable.
    """

    class ObservationType(models.TextChoices):
        ASKING = "asking", "Asking Price"
        SOLD = "sold", "Sold Price"

    product_key = models.CharField(
        max_length=300,
        db_index=True,
        help_text="Normalized brand/model key for cross-scan aggregation.",
    )
    identified_item = models.ForeignKey(
        "scans.IdentifiedItem",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="market_observations",
        help_text="Linked scan result, if applicable.",
    )
    source = models.CharField(
        max_length=100,
        help_text="Where this observation came from, e.g. 'ebay', 'stockx'.",
    )
    observed_price = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        validators=[MinValueValidator(0.01)],
        help_text="Observed price. Must be > 0.",
    )
    currency = models.CharField(
        max_length=3,
        default="USD",
        help_text="ISO 4217 currency code.",
    )
    observation_type = models.CharField(
        max_length=10,
        choices=ObservationType.choices,
        help_text="Whether this is an asking price or a confirmed sale.",
    )
    observed_on = models.DateField(
        help_text="Date the price was observed on the marketplace.",
    )
    collected_at = models.DateTimeField(
        auto_now_add=True,
        help_text="When this record was ingested into ValuLens.",
    )

    class Meta:
        db_table = "pricing_market_price_observation"
        verbose_name = "market price observation"
        verbose_name_plural = "market price observations"
        ordering = ["-observed_on"]
        indexes = [
            models.Index(
                fields=["product_key", "observation_type", "observed_on"],
                name="idx_observation_key_type_date",
            ),
            models.Index(
                fields=["product_key", "-observed_on"],
                name="idx_observation_key_date_desc",
            ),
        ]
        constraints = [
            # Price must be positive
            models.CheckConstraint(
                name="ck_observation_price_positive",
                condition=models.Q(observed_price__gt=0),
            ),
        ]

    def __str__(self):
        return (
            f"{self.product_key}: {self.currency} {self.observed_price} "
            f"({self.get_observation_type_display()}) on {self.observed_on}"
        )
