"""
MOCK recognition provider for local development and tests.

It does NOT identify anything. Output is derived deterministically from the
image hash so the pipeline (including the low-confidence path) can be
exercised end to end. Every result is labelled MOCK in the stored provider
name, the title, the attributes, and the logs.
"""

import hashlib
import io
from decimal import Decimal

from PIL import Image

from .base import RecognitionProvider, RecognitionResult

MOCK_CONFIDENCE_MIN = Decimal("0.30")
MOCK_CONFIDENCE_MAX = Decimal("0.95")


class MockRecognitionProvider(RecognitionProvider):
    name = "MOCK"
    is_mock = True

    def recognize(self, image_bytes: bytes, content_type: str, *, timeout: int) -> RecognitionResult:
        digest = hashlib.sha256(image_bytes).digest()
        spread = MOCK_CONFIDENCE_MAX - MOCK_CONFIDENCE_MIN
        confidence = (MOCK_CONFIDENCE_MIN + spread * Decimal(digest[0]) / Decimal(255)).quantize(
            Decimal("0.01")
        )
        with Image.open(io.BytesIO(image_bytes)) as image:
            width, height = image.size

        return RecognitionResult(
            title="MOCK result - not a real identification",
            confidence=confidence,
            attributes={
                "mock": True,
                "notice": "Generated by the MOCK provider for development. No recognition was performed.",
                "image_width": width,
                "image_height": height,
            },
        )
