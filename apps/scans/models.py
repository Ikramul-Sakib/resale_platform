"""
Scan models for ValuLens.

Covers the full scan lifecycle: upload → processing → identification.
- Scan: the scan session (one per user action)
- ScanImage: uploaded image(s) attached to a scan
- IdentifiedItem: the recognition result for a scan
"""

import uuid
from decimal import Decimal

from django.conf import settings
from django.db import models
from django.core.validators import MinValueValidator, MaxValueValidator


class Scan(models.Model):
    """
    A scan session initiated by a user (or guest).

    Lifecycle: pending → processing → completed | failed.

    Guest scans use session_key instead of user FK, are rate-limited,
    and auto-purged after GUEST_SCAN_RETENTION_HOURS.
    """

    class Status(models.TextChoices):
        PENDING = "pending", "Pending"
        PROCESSING = "processing", "Processing"
        COMPLETED = "completed", "Completed"
        FAILED = "failed", "Failed"

    public_id = models.UUIDField(
        default=uuid.uuid4,
        editable=False,
        unique=True,
        help_text="Public-facing identifier for API/URL use.",
    )
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        null=True,
        blank=True,
        related_name="scans",
        help_text="Owner. Null for guest scans (identified by session_key).",
    )
    session_key = models.CharField(
        max_length=40,
        blank=True,
        default="",
        db_index=True,
        help_text="Django session key for guest scans. Empty for authenticated users.",
    )
    status = models.CharField(
        max_length=10,
        choices=Status.choices,
        default=Status.PENDING,
        db_index=True,
    )
    error_message = models.TextField(
        blank=True,
        default="",
        help_text="User-safe error message. Set only when status is 'failed'.",
    )
    created_at = models.DateTimeField(auto_now_add=True)
    completed_at = models.DateTimeField(
        null=True,
        blank=True,
        help_text="Set only when status is 'completed' or 'failed'.",
    )

    class Meta:
        db_table = "scans_scan"
        verbose_name = "scan"
        verbose_name_plural = "scans"
        ordering = ["-created_at"]
        indexes = [
            models.Index(fields=["user", "-created_at"], name="idx_scan_user_created"),
        ]
        constraints = [
            # completed_at must be NULL unless status is completed or failed
            models.CheckConstraint(
                name="ck_scan_completed_at_status",
                condition=(
                    models.Q(
                        status__in=["completed", "failed"],
                    )
                    | models.Q(completed_at__isnull=True)
                ),
            ),
        ]

    def __str__(self):
        owner = self.user.email if self.user else f"guest:{self.session_key[:8]}"
        return f"Scan {self.public_id!s:.8} ({owner}) [{self.status}]"


class ScanImage(models.Model):
    """
    An image uploaded as part of a Scan.

    Images are stored via Django's storage backend (local in dev,
    S3-compatible in prod). The DB stores only metadata — never
    the binary content.
    """

    scan = models.ForeignKey(
        Scan,
        on_delete=models.CASCADE,
        related_name="images",
        help_text="The scan this image belongs to.",
    )
    storage_key = models.CharField(
        max_length=500,
        help_text="Storage backend key (path or S3 object key).",
    )
    content_type = models.CharField(
        max_length=50,
        help_text="MIME type, e.g. 'image/jpeg'. Validated against allowlist.",
    )
    file_size = models.PositiveIntegerField(
        help_text="File size in bytes.",
    )
    sha256 = models.CharField(
        max_length=64,
        help_text="SHA-256 hex digest for integrity verification.",
    )
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = "scans_scan_image"
        verbose_name = "scan image"
        verbose_name_plural = "scan images"
        ordering = ["created_at"]

    def __str__(self):
        return f"Image {self.pk} for Scan {self.scan.public_id!s:.8}"


class IdentifiedItem(models.Model):
    """
    The result of running a recognition provider on a Scan.

    May be auto-generated by a provider or manually corrected by the user.
    Confidence is provider-reported (0.0–1.0). When is_user_corrected=True,
    the user has overridden the provider's prediction.
    """

    class Condition(models.TextChoices):
        NEW_WITH_TAGS = "new_with_tags", "New with Tags"
        NEW_WITHOUT_TAGS = "new_without_tags", "New without Tags"
        EXCELLENT = "excellent", "Excellent"
        VERY_GOOD = "very_good", "Very Good"
        GOOD = "good", "Good"
        FAIR = "fair", "Fair"
        POOR = "poor", "Poor"
        UNKNOWN = "unknown", "Unknown"

    scan = models.OneToOneField(
        Scan,
        on_delete=models.CASCADE,
        related_name="identified_item",
        help_text="The scan that produced this identification.",
    )
    category = models.ForeignKey(
        "catalog.Category",
        on_delete=models.PROTECT,
        related_name="identified_items",
        help_text="Product category. PROTECT: cannot delete a category in use.",
    )
    brand = models.ForeignKey(
        "catalog.Brand",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="identified_items",
        help_text="Product brand. SET_NULL: brand deletion does not cascade.",
    )
    title = models.CharField(
        max_length=300,
        help_text="Human-readable title, e.g. 'Nike Air Max 90 White'.",
    )
    model_name = models.CharField(
        max_length=200,
        blank=True,
        default="",
        help_text="Model/SKU identifier when available.",
    )
    condition = models.CharField(
        max_length=20,
        choices=Condition.choices,
        default=Condition.GOOD,
        help_text="Assessed condition of the item.",
    )
    attributes = models.JSONField(
        default=dict,
        blank=True,
        help_text="Additional attributes: color, size, material, etc. (JSONB).",
    )
    confidence = models.DecimalField(
        max_digits=3,
        decimal_places=2,
        validators=[MinValueValidator(0), MaxValueValidator(1)],
        help_text="Provider confidence score (0.00–1.00).",
    )
    provider_name = models.CharField(
        max_length=50,
        help_text="Name of the recognition provider, e.g. 'mock', 'google_vision'.",
    )
    is_user_corrected = models.BooleanField(
        default=False,
        help_text="True if the user manually corrected the provider's prediction.",
    )
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = "scans_identified_item"
        verbose_name = "identified item"
        verbose_name_plural = "identified items"
        ordering = ["-created_at"]
        constraints = [
            # Confidence must be between 0 and 1
            models.CheckConstraint(
                name="ck_identified_item_confidence_range",
                condition=models.Q(confidence__gte=0, confidence__lte=1),
            ),
        ]

    @property
    def is_mock(self):
        """True when produced by a MOCK provider (no real recognition)."""
        return self.provider_name.upper().startswith("MOCK")

    @property
    def is_low_confidence(self):
        """True when confidence is below RECOGNITION_LOW_CONFIDENCE_THRESHOLD."""
        return Decimal(self.confidence) < settings.RECOGNITION_LOW_CONFIDENCE_THRESHOLD

    def __str__(self):
        brand_str = f"{self.brand.name} " if self.brand else ""
        return f"{brand_str}{self.title} ({self.get_condition_display()})"
